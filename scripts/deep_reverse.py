def build(out: Path = Path("역설계_심화_제형별.xlsx")) -> Path:
    thin = Side(style="thin", color="D8DCE3")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    wrap = Alignment(wrap_text=True, vertical="top")
    wb = openpyxl.Workbook()
    first = True
    for tab, product, oneline, skel, sections in PRODUCTS:
        ws = wb.active if first else wb.create_sheet(tab)
        if first:
            ws.title = tab
            first = False
        ws.column_dimensions["A"].width = 30
        ws.column_dimensions["B"].width = 108

        r = 1
        ws.merge_cells(f"A{r}:B{r}")
        t = ws.cell(r, 1, f"[{tab}]  {product} — 역설계 심화")
        t.font = Font(bold=True, size=14, color="33475B")
        ws.row_dimensions[r].height = 22
        r += 1
        ws.merge_cells(f"A{r}:B{r}")
        n = ws.cell(r, 1, NOTE)
        n.font = Font(size=9, color="7A4A2A")
        n.fill = PatternFill("solid", fgColor="FDECE0")
        n.alignment = wrap
        ws.row_dimensions[r].height = 28
        r += 1

        for label, val in (("한 줄 요약", oneline), ("골격(%)", skel)):
            lc = ws.cell(r, 1, label)
            lc.font = Font(bold=True, size=10)
            lc.fill = PatternFill("solid", fgColor="EFF4FB")
            lc.alignment = wrap
            lc.border = border
            bc = ws.cell(r, 2, val)
            bc.alignment = wrap
            bc.border = border
            ws.row_dimensions[r].height = max(28, -(-len(val) // 52) * 15)
            r += 1

        for sub, body in sections:
            lc = ws.cell(r, 1, sub)
            lc.font = Font(bold=True, size=10, color="5B3A7A")
            lc.fill = PatternFill("solid", fgColor="F3EEFA")
            lc.alignment = wrap
            lc.border = border
            bc = ws.cell(r, 2, body)
            bc.alignment = wrap
            bc.border = border
            nlines = sum(max(1, -(-len(ln) // 52)) for ln in body.split("\n"))
            ws.row_dimensions[r].height = max(30, nlines * 15)
            r += 1
        ws.freeze_panes = "A2"

    # 공통교훈 탭
    cs = wb.create_sheet("공통교훈")
    cs.column_dimensions["A"].width = 120
    cs.cell(1, 1, "다섯 처방이 공통으로 가르치는 것").font = Font(bold=True, size=13, color="33475B")
    rr = 2
    for line in COMMON:
        c = cs.cell(rr, 1, line)
        c.alignment = wrap
        c.fill = PatternFill("solid", fgColor="F7FAFF")
        c.border = border
        cs.row_dimensions[rr].height = max(24, -(-len(line) // 58) * 16)
        rr += 1
    cs.cell(rr + 1, 1, NOTE).font = Font(size=9, color="7A4A2A")

    wb.save(out)
    print(f"역설계 심화 → {out.name}: 제형 {len(PRODUCTS)}탭 + 공통교훈")
    return out


if __name__ == "__main__":
    build()
