def preserve_inputs() -> dict[str, tuple]:
    """기존 원료_마스터의 사용자 입력(손테스트·메모·숙련도)을 원료명 키로 보존."""
    if not OUT.exists():
        return {}
    wb = openpyxl.load_workbook(OUT)
    if "원료 카드" not in wb.sheetnames:
        return {}
    ws = wb["원료 카드"]
    hdr = {ws.cell(4, j).value: j for j in range(1, ws.max_column + 1)}  # 헤더 이름 기준(열 추가에도 안전)
    idx = [hdr.get(c[0]) for c in INPUT_COLS]
    keep = {}
    for r in range(5, ws.max_row + 1):
        name = ws.cell(r, hdr.get("원료", 2)).value
        vals = tuple(ws.cell(r, j).value if j else None for j in idx)
        if name and any(v not in (None, "") for v in vals):
            keep[name] = vals
    return keep


