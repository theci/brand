def build_queue(wb, keep):
    """도감(기능성 전체 + 허브누리 등장 QUEUE_MIN회↑ 단일 원료) 중 카드 미수록 → 다음 공부 대기열."""
    ws = wb.create_sheet("다음 공부")
    title(ws, "다음 공부 대기열 — 원료 도감에서 아직 카드가 없는 원료",
          f"제품개발_마스터 '원료 도감'에서 자동 추출: 기능성 전체 + 허브누리 등장 {QUEUE_MIN}회↑ 단일 원료. 블렌드·상품명 원료는 '블렌드 해부' 시트로, 완제 베이스·방향제는 제외. "
          "이름 표기 차이로 이미 카드가 있는 원료가 섞일 수 있음 — '후보' 목록. 관심 원료는 스크립트 카드 파일에 한 줄 추가 → 재생성. 상태 칸은 자유 입력(재생성해도 보존).", 7)
    header(ws, 4, ["구분", "역할", "원료(도감)", "등장수", "전형/사용%", "기능·특징(도감)", "상태"], [10, 12, 36, 8, 16, 60, 10])
    if not SRC.exists():
        ws.cell(5, 1, "제품개발_마스터.xlsx 없음")
        return
    src = openpyxl.load_workbook(SRC, read_only=True)["원료 도감"]
    have = {_nkey(c[0].split("(")[0]) for c in CARDS} | {_nkey(c[0]) for c in CARDS} \
        | {c[1].lower().split(" (")[0] for c in CARDS}
    have.discard("")
    r = 5
    for row in src.iter_rows(min_row=4, values_only=True):
        if not row[0] or row[3] not in ("기능성", "허브누리"):
            continue
        name = row[0].split("\n")[0]
        if row[3] == "허브누리" and ((row[4] or 0) < QUEUE_MIN or row[1] in _SKIP_ROLES
                                    or any(w in name for w in _SKIP_WORDS)
                                    or name in BLEND_NAMES or name in NOT_COSMETIC):
            continue
        k = _nkey(name.split("(")[0]) if row[3] == "기능성" else _nkey(name)
        inci = name.split("(")[-1].rstrip(")").lower() if "(" in name else ""
        if any(k and (k in h or h in k) for h in have if len(h) > 2) or (inci and inci in have) \
                or any(name.startswith(a) for a in COVERED_ALIASES):
            continue
        pct = row[2] if row[3] == "기능성" else row[5]
        for j, v in enumerate([row[3], row[1], name, row[4], pct, row[6]], 1):
            c = ws.cell(r, j, v)
            c.alignment = WRAP
            c.border = BORDER
            c.font = f()
        ws.cell(r, 7, keep.get(name)).fill = INPUT_FILL
        ws.cell(r, 7).border = BORDER
        r += 1
    ws.auto_filter.ref = f"A4:G{max(r - 1, 5)}"
    ws.freeze_panes = "D5"
    print(f"다음 공부 대기열 {r - 5}건")


